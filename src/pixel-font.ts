const parsed = new Map(
  Object.entries(glyphs).map(([k, v]) => [k, v.split("/")]),
);
export function textWidth(text: string, size: number) {
  let w = 0;
  for (const c of text.toUpperCase())
    w += (c === " " ? 4 : (parsed.get(c)?.[0].length ?? 5) + 1) * size;
  return Math.max(0, w - size);
}
export function pixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  size: number,
  color: string,
  align: "left" | "center" | "right" = "left",
) {
  x = Math.round(
    x -
      (align === "center"
        ? textWidth(text, size) / 2
        : align === "right"
          ? textWidth(text, size)
          : 0),
  );
  y = Math.round(y);
  ctx.fillStyle = color;
  for (const c of text.toUpperCase()) {
    if (c === " ") {
      x += 4 * size;
      continue;
    }
    const rows = parsed.get(c) ?? parsed.get("?")!;
    for (let r = 0; r < 7; r++)
      for (let col = 0; col < rows[r].length; col++)
        if (rows[r][col] === "1")
          ctx.fillRect(x + col * size, y + r * size, size, size);
    x += (rows[0].length + 1) * size;
  }
}
